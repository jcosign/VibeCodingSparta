def chunk(text: str, size: int = 40):
    """긴 텍스트를 size 글자 단위로 자른다(청킹). 짧으면 그대로."""
    text = text.strip()
    if len(text) <= size:
        return [text]                                         # 짧으면 통째로 (조각 1개)
    return [text[i:i+size] for i in range(0, len(text), size)]


